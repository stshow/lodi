/// An HTML page where a keyring should be. It declares its own digest in the tests below, so that
/// the framing check (which follows the digest check) is what refuses it.
const PAGE: &[u8] = b"<!doctype html><title>keys</title>\n";

/// Every failure of the fetch ends the apply with its code and nothing written anywhere — also
/// when the manifest's other source is valid and was planned first.
#[test]
fn every_fetch_failure_ends_the_apply_with_nothing_written() {
    let key = public_binary();
    let sha = sha256_hex(&key);
    let big = {
        let mut big = public_binary();
        big.resize(sources::MAX_KEYRING_BYTES + 1, 0);
        big
    };
    let server = Server::start(&[
        ("/gone.gpg", Reply::Body(404, b"no such key\n".to_vec())),
        ("/big.gpg", Reply::Body(200, big.clone())),
        ("/rotated.gpg", Reply::Body(200, public_armored())),
        ("/secret.gpg", Reply::Body(200, public_then_secret())),
        ("/private.asc", Reply::Body(200, armored_then_private())),
        ("/page.gpg", Reply::Body(200, PAGE.to_vec())),
        (
            "/moved.gpg",
            Reply::Redirect("http://keys.example.invalid/docker.gpg".into()),
        ),
    ]);
    for (path, digest, code, exit, words) in [
        ("gone.gpg", sha.clone(), "E_FETCH", 5, "HTTP status 404"),
        (
            "big.gpg",
            sha256_hex(&big),
            "E_FETCH",
            5,
            "body larger than 1048576 bytes",
        ),
        (
            "rotated.gpg",
            sha.clone(),
            "E_HASH_MISMATCH",
            5,
            "rotated its signing key",
        ),
        (
            "secret.gpg",
            sha256_hex(&public_then_secret()),
            "E_TYPE",
            3,
            "secret key material",
        ),
        (
            "private.asc",
            sha256_hex(&armored_then_private()),
            "E_TYPE",
            3,
            "secret key material",
        ),
        (
            "page.gpg",
            sha256_hex(PAGE),
            "E_TYPE",
            3,
            "not an OpenPGP public keyring",
        ),
        (
            "moved.gpg",
            sha.clone(),
            "E_INSECURE_URL",
            5,
            "not an HTTPS URL",
        ),
    ] {
        let elsewhere = Elsewhere::new(&format!("fail-{path}"));
        // `other` sorts after `docker`, so a partial apply would have had something to write.
        let manifest = format!("{}\n{}", by_url(path, &digest), by_path(&sha));
        let case = armed(&format!("fetch-fail-{path}"), &manifest);
        let root_before = tree(&case.root.dir);
        let elsewhere_before = tree(&elsewhere.dir);
        let connections = server.connections();

        let apply = lodi("apply", &case, &server, &elsewhere);
        let out = text(&apply);
        assert_eq!(apply.status.code(), Some(exit), "{path}: {out}");
        assert!(out.contains(code), "{path}: expected {code}: {out}");
        assert!(out.contains(words), "{path}: expected {words:?}: {out}");
        assert!(out.contains("[sources.docker]"), "{path}: {out}");
        assert_eq!(server.connections(), connections + 1, "{path}");

        assert_eq!(
            tree(&case.root.dir),
            root_before,
            "{path}: the apply wrote below the root"
        );
        assert_eq!(
            tree(&elsewhere.dir),
            elsewhere_before,
            "{path}: the apply cached something outside the root"
        );
        assert!(journals(&case.root).is_empty(), "{path}");
        // The plan beside it is unchanged by the failure: still a fetch, still no request.
        let plan = lodi("plan", &case, &server, &elsewhere);
        assert!(plan.status.success(), "{path}: {}", text(&plan));
        assert!(
            text(&plan).contains("+ source docker (keyring: fetch, sources)"),
            "{path}: {}",
            text(&plan)
        );
        assert_eq!(
            server.connections(),
            connections + 1,
            "{path}: plan fetched"
        );
    }
}

/// A waiter that never sleeps: the one fetch this is used for is made once.
struct NoWait;

impl Waiter for NoWait {
    fn notice(&self, _line: &str) {}
    fn wait(&self, _d: Duration) {}
    fn random(&self) -> f64 {
        0.0
    }
}

#[test]
fn a_server_that_never_answers_ends_the_apply_with_e_fetch_and_nothing_written() {
    let server = Server::start(&[("/docker.gpg", Reply::Stall)]);
    let key = public_binary();
    let manifest = format!(
        "{}\n{}",
        by_url("docker.gpg", &sha256_hex(&key)),
        by_path(&sha256_hex(&key))
    );
    let root = armed_in_place("fetch-timeout", &manifest);
    let before = tree(&root.dir);
    // `lodi`'s own fetcher with only its limits shortened: 60 s for the headers is `lodi`'s
    // rule, and one second is the same rule, sooner.
    let fetcher = HttpFetcher::with_retry(
        vec![Rewrite {
            prefix: KEYS.into(),
            replacement: format!("http://127.0.0.1:{}/", server.port),
        }],
        FetchTimeouts {
            resolve: Duration::from_secs(5),
            connect: Duration::from_secs(5),
            send: Duration::from_secs(5),
            headers: Duration::from_secs(1),
            stall: Duration::from_secs(1),
            min_rate: 1,
        },
        Retry::ONCE,
        Arc::new(NoWait),
    );
    let started = Instant::now();
    let error = lodi::hostscope::apply_with(&root.options(), Some(&fetcher))
        .expect_err("the server never answers");
    assert!(started.elapsed() < Duration::from_secs(20));
    assert_eq!(error.codes(), vec!["E_FETCH"], "{error}");
    assert_eq!(error.exit_status(), 5);
    assert!(error.to_string().contains("[sources.docker]"), "{error}");
    assert_eq!(server.connections(), 1);
    assert_eq!(tree(&root.dir), before, "the apply wrote below the root");
    assert!(journals(&root).is_empty());
}

/// A passing apply leaves exactly what the same source with its keyring beside the manifest
/// leaves — the two managed files, the lock, the host state — and nothing that could be a cache.
#[test]
fn a_keyring_by_url_leaves_nothing_a_keyring_by_path_does_not() {
    let key = public_binary();
    let sha = sha256_hex(&key);
    let server = Server::start(&[("/docker.gpg", Reply::Body(200, key.clone()))]);

    let elsewhere = Elsewhere::new("shape-url");
    let url_case = armed("fetch-shape-url", &by_url("docker.gpg", &sha));
    let url_before: BTreeSet<String> = tree(&url_case.root.dir).into_keys().collect();
    let apply = lodi("apply", &url_case, &server, &elsewhere);
    assert!(apply.status.success(), "{}", text(&apply));
    let url_added: BTreeSet<String> = tree(&url_case.root.dir)
        .into_keys()
        .filter(|path| !url_before.contains(path))
        .collect();
    assert!(
        tree(&elsewhere.dir).values().all(Option::is_none),
        "a file appeared outside the root: {:?}",
        tree(&elsewhere.dir)
    );

    let path_manifest = by_url("docker.gpg", &sha).replace(
        &format!("signed_by_url = \"{KEYS}docker.gpg\""),
        "signed_by = \"files/docker.gpg\"",
    );
    let path_case = armed("fetch-shape-path", &path_manifest);
    path_case.write_beside("files/docker.gpg", &key);
    let path_before: BTreeSet<String> = tree(&path_case.root.dir).into_keys().collect();
    let apply = lodi("apply", &path_case, &server, &elsewhere);
    assert!(apply.status.success(), "{}", text(&apply));
    let path_added: BTreeSet<String> = tree(&path_case.root.dir)
        .into_keys()
        .filter(|path| !path_before.contains(path))
        .collect();

    assert_eq!(url_added, path_added);
    // Of what the apply wrote, the fetched bytes are in exactly one file: the managed keyring.
    let copies: Vec<String> = tree(&url_case.root.dir)
        .into_iter()
        .filter(|(path, digest)| {
            url_added.contains(path) && digest.as_deref() == Some(sha.as_str())
        })
        .map(|(path, _)| path)
        .collect();
    assert_eq!(copies, vec!["etc/apt/keyrings/lodi-docker.gpg".to_string()]);
    assert_eq!(server.connections(), 1);
}

// ------------------------------------------- the landed core's rules, on the URL path ---
//
// The validator repair of the landed core (PR 115) made four of its rules true for a keyring by
// path: a URI fragment is `E_TYPE` named at its place (S2), a private-key block anywhere in the
// bytes is refused before they are copied (S4), a link above either apt source path is refused
// (S7), and a hand edit of a managed keyring or stanza is `E_DRIFT` until `--overwrite-drift`
// (S10). Each is exercised here on a keyring by URL, through the binary, with the loopback
// server counting every request.

/// S2 for `signed_by_url`: a fragment is `E_TYPE`, named, at the value's file:line:column — on
/// the plan and on the apply, before any request and with nothing written.
#[test]
fn a_fragment_in_signed_by_url_is_e_type_naming_it_at_its_place_before_any_request() {
    let key = public_binary();
    let server = Server::start(&[("/docker.gpg", Reply::Body(200, key.clone()))]);
    let elsewhere = Elsewhere::new("fragment");
    let case = armed(
        "fetch-fragment",
        &by_url("docker.gpg#main", &sha256_hex(&key)),
    );
    let manifest = case.manifest();
    let line = manifest
        .lines()
        .position(|line| line.starts_with("signed_by_url = "))
        .expect("the key's line")
        + 1;
    let before = tree(&case.root.dir);
    for verb in ["plan", "apply"] {
        let output = lodi(verb, &case, &server, &elsewhere);
        let out = text(&output);
        assert_eq!(output.status.code(), Some(3), "{verb}: {out}");
        assert!(out.contains("E_TYPE"), "{verb}: {out}");
        assert!(
            out.contains("carries a fragment (`#main`)"),
            "{verb}: {out}"
        );
        // `signed_by_url = "` is 16 columns: the value starts at the 17th.
        assert!(
            out.contains(&format!("host.toml:{line}:17")),
            "{verb}: {out}"
        );
    }
    assert_eq!(server.connections(), 0, "a request was made");
    assert_eq!(tree(&case.root.dir), before, "something was written");
}

/// S10 for a keyring by URL: a hand edit of the fetched keyring, or of its stanza, is `W_DRIFT`
/// on the plan and `E_DRIFT` (exit 8) on the apply — decided from the lock and the file, before
/// any request, with nothing written — until `--overwrite-drift` puts the declared bytes back.
#[test]
fn a_hand_edit_of_a_keyring_by_url_or_its_stanza_is_e_drift_before_any_request() {
    let key = public_binary();
    let server = Server::start(&[("/docker.gpg", Reply::Body(200, key.clone()))]);
    for (index, path) in [
        "etc/apt/keyrings/lodi-docker.gpg",
        "etc/apt/sources.list.d/lodi-docker.sources",
    ]
    .into_iter()
    .enumerate()
    {
        let elsewhere = Elsewhere::new(&format!("drift-{index}"));
        let case = armed(
            &format!("fetch-drift-{index}"),
            &by_url("docker.gpg", &sha256_hex(&key)),
        );
        let apply = lodi("apply", &case, &server, &elsewhere);
        assert!(apply.status.success(), "{path}: {}", text(&apply));
        let stanza = case.root.read("etc/apt/sources.list.d/lodi-docker.sources");
        let connections = server.connections();

        case.root.write(path, "edited by hand\n");
        let plan = lodi("plan", &case, &server, &elsewhere);
        let out = text(&plan);
        assert!(plan.status.success(), "{path}: {out}");
        assert!(
            out.contains(&format!(
                "W_DRIFT: /{path} was changed since lodi last wrote it"
            )),
            "{path}: {out}"
        );
        assert!(out.contains("~ source docker ("), "{path}: {out}");
        assert_eq!(server.connections(), connections, "{path}: plan fetched");

        let lock = case.root.read("etc/lodi/host.lock");
        let before = tree(&case.root.dir);
        let apply = lodi("apply", &case, &server, &elsewhere);
        let out = text(&apply);
        assert_eq!(apply.status.code(), Some(8), "{path}: {out}");
        assert!(
            out.contains(&format!(
                "E_DRIFT: /{path} of a declared source was changed since lodi last wrote it"
            )),
            "{path}: {out}"
        );
        assert!(out.contains("--overwrite-drift"), "{path}: {out}");
        assert_eq!(
            server.connections(),
            connections,
            "{path}: the apply made a request before it refused the drift"
        );
        assert_eq!(case.root.read(path), "edited by hand\n", "{path}");
        assert_eq!(case.root.read("etc/lodi/host.lock"), lock, "{path}");
        assert_eq!(
            tree(&case.root.dir),
            before,
            "{path}: something was written"
        );

        let apply = lodi_with("apply", &["--overwrite-drift"], &case, &server, &elsewhere);
        assert!(apply.status.success(), "{path}: {}", text(&apply));
        assert_eq!(
            fs::read(case.root.path("etc/apt/keyrings/lodi-docker.gpg")).unwrap(),
            key,
            "{path}"
        );
        assert_eq!(
            case.root.read("etc/apt/sources.list.d/lodi-docker.sources"),
            stanza,
            "{path}"
        );
        // Only the edited keyring had to be fetched again; an edited stanza beside a verified
        // keyring is put back from the file at the managed path.
        let fetched = usize::from(path.ends_with(".gpg"));
        assert_eq!(server.connections(), connections + fetched, "{path}");
    }
}

/// S7 for a keyring by URL: a link above the apt source paths — `/etc/apt` itself — is the same
/// `E_SYNTAX` a keyring by path gets, before any request and with nothing written; also when the
/// fetched keyring is already there behind it.
#[test]
fn a_link_above_the_apt_source_paths_is_e_syntax_for_a_keyring_by_url_before_any_request() {
    let key = public_binary();
    let server = Server::start(&[("/docker.gpg", Reply::Body(200, key.clone()))]);
    for (index, applied_first) in [false, true].into_iter().enumerate() {
        let elsewhere = Elsewhere::new(&format!("parent-link-{index}"));
        let case = armed(
            &format!("fetch-parent-link-{index}"),
            &by_url("docker.gpg", &sha256_hex(&key)),
        );
        if applied_first {
            let apply = lodi("apply", &case, &server, &elsewhere);
            assert!(apply.status.success(), "{}", text(&apply));
        }
        let connections = server.connections();
        // `/etc/apt` becomes a link to a directory elsewhere below the root.
        let apt = case.root.path("etc/apt");
        let moved = case.root.path("elsewhere/apt");
        fs::create_dir_all(case.root.path("elsewhere")).expect("a directory");
        if apt.exists() {
            fs::rename(&apt, &moved).expect("moved aside");
        }
        fs::create_dir_all(moved.join("sources.list.d")).expect("a directory");
        std::os::unix::fs::symlink("../elsewhere/apt", &apt).expect("the link");
        let before = tree(&case.root.dir);
        for verb in ["plan", "apply"] {
            let output = lodi(verb, &case, &server, &elsewhere);
            let out = text(&output);
            assert_eq!(output.status.code(), Some(3), "{index} {verb}: {out}");
            assert!(out.contains("E_SYNTAX"), "{index} {verb}: {out}");
            assert!(
                out.contains("/etc/apt on the way to it is a symbolic link"),
                "{index} {verb}: {out}"
            );
        }
        assert_eq!(
            server.connections(),
            connections,
            "{index}: a request was made"
        );
        assert_eq!(
            tree(&case.root.dir),
            before,
            "{index}: something was written"
        );
    }
}

