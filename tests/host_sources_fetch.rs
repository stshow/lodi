fn context() -> Context {
    Context {
        arch: "x86_64".into(),
        os: "linux".into(),
        distro: "debian".into(),
        release: "12".into(),
        codename: "bookworm".into(),
        lodi_version: env!("CARGO_PKG_VERSION").into(),
    }
}

fn parse(text: &str) -> HostManifest {
    match parse_host(text, "host.toml", &context()) {
        Ok(manifest) => manifest,
        Err(errors) => panic!("expected a valid manifest, got:\n{errors}"),
    }
}

#[track_caller]
fn rejects(text: &str, code: &'static str) -> ManifestErrors {
    let errors = match parse_host(text, "host.toml", &context()) {
        Ok(_) => panic!("expected {code}, the manifest parsed"),
        Err(errors) => errors,
    };
    assert!(
        errors.codes().contains(&code),
        "expected {code}, got {:?}:\n{errors}",
        errors.codes()
    );
    errors
}

/// `[sources.docker]` with `line` in place of its keyring line.
fn keyed(line: &str) -> String {
    format!(
        "[vars]\nscheme = \"http\"\n\n[sources.docker]\n\
         uris = [\"https://download.docker.com/linux/debian\"]\n\
         suites = [\"bookworm\"]\n\
         components = [\"stable\"]\n\
         {line}\n\
         signed_by_sha256 = \"{}\"\n",
        "a".repeat(64)
    )
}

#[test]
fn signed_by_url_is_https_without_user_information_and_exactly_one_keyring_is_named() {
    let manifest = parse(&keyed(&format!("signed_by_url = \"{KEYS}docker.gpg\"")));
    let entry = &manifest.sources["docker"];
    assert_eq!(
        entry.signed_by_url.as_deref(),
        Some("https://keys.example.invalid/docker.gpg")
    );
    assert_eq!(entry.signed_by, "");

    for (url, code) in [
        ("http://keys.example.invalid/docker.gpg", "E_INSECURE_URL"),
        (
            "${vars.scheme}://keys.example.invalid/docker.gpg",
            "E_INSECURE_URL",
        ),
        ("ftp://keys.example.invalid/docker.gpg", "E_INSECURE_URL"),
        ("file:///etc/apt/keyrings/docker.gpg", "E_INSECURE_URL"),
        ("keys.example.invalid/docker.gpg", "E_INSECURE_URL"),
        ("https:///docker.gpg", "E_INSECURE_URL"),
        ("https://keys.example.invalid/docker.gpg?v=1", "E_TYPE"),
        ("https://keys.example.invalid/docker.gpg#key", "E_TYPE"),
        ("https://keys.example.invalid/a b", "E_TYPE"),
        ("", "E_TYPE"),
    ] {
        let errors = rejects(&keyed(&format!("signed_by_url = \"{url}\"")), code);
        let shown = errors.to_string();
        assert!(
            shown.contains("`signed_by_url` in [sources.docker]"),
            "{shown}"
        );
    }

    // Credentials are refused by name, and never repeated.
    for url in [
        "https://user@192.0.2.1/docker.gpg",
        "https://user:hunter2-password@192.0.2.1/docker.gpg",
    ] {
        let errors = rejects(
            &keyed(&format!("signed_by_url = \"{url}\"")),
            "E_INSECURE_URL",
        );
        let shown = errors.to_string();
        assert!(shown.contains("user information"), "{shown}");
        assert!(!shown.contains("hunter2"), "{shown}");
        assert!(!shown.contains("user@"), "{shown}");
    }

    // Both, or neither, is a conflict.
    let both = keyed(&format!(
        "signed_by = \"files/docker.gpg\"\nsigned_by_url = \"{KEYS}docker.gpg\""
    ));
    let shown = rejects(&both, "E_ATTR_CONFLICT").to_string();
    assert!(
        shown.contains("both of `signed_by` and `signed_by_url`"),
        "{shown}"
    );
    let shown = rejects(&keyed(""), "E_ATTR_CONFLICT").to_string();
    assert!(
        shown.contains("declares no `signed_by` and no `signed_by_url`"),
        "{shown}"
    );
}

#[test]
fn the_framing_check_names_a_public_keyring_and_refuses_everything_else() {
    assert_eq!(sources::sniff(&public_binary()), Ok(Format::Binary));
    assert_eq!(sources::sniff(&public_armored()), Ok(Format::Armored));
    // Two public keys are a keyring apt trusts every key of.
    let mut two = public_binary();
    two.extend(public_binary());
    assert_eq!(sources::sniff(&two), Ok(Format::Binary));
    // An old-format header (tag 6, two-octet length) frames a key too.
    let mut old = vec![0x99, 0x00, 0x05];
    old.extend_from_slice(b"\x04abcd");
    assert_eq!(sources::sniff(&old), Ok(Format::Binary));

    assert_eq!(sources::sniff(&public_then_secret()), Err(Refusal::Secret));
    assert_eq!(
        sources::sniff(&armored_then_private()),
        Err(Refusal::Secret)
    );
    assert_eq!(
        sources::sniff(&packet(7, b"\x04secret subkey")),
        Err(Refusal::Secret)
    );
    let mut truncated = public_binary();
    truncated.truncate(truncated.len() - 3);
    for refused in [
        Vec::new(),
        truncated,
        b"<!doctype html><html><body>404</body></html>\n".to_vec(),
        b"just some text\n".to_vec(),
        packet(13, b"a user id first"),
    ] {
        assert_eq!(sources::sniff(&refused), Err(Refusal::NotKeyring));
    }
}

