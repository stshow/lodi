/// One new-format OpenPGP packet: the tag, a one-octet length, and `body`.
fn packet(tag: u8, body: &[u8]) -> Vec<u8> {
    assert!(body.len() < 192);
    let mut out = vec![0xc0 | tag, body.len() as u8];
    out.extend_from_slice(body);
    out
}

/// A binary public keyring as far as framing goes: a public-key packet (tag 6) and a user id
/// (tag 13). The key material is invented; nothing reads it.
fn public_binary() -> Vec<u8> {
    let mut out = packet(6, b"\x04invented public key material");
    out.extend(packet(13, b"invented test key"));
    out
}

fn public_armored() -> Vec<u8> {
    b"-----BEGIN PGP PUBLIC KEY BLOCK-----\n\nbW9ja2VkIGtleQ==\n=AAAA\n-----END PGP PUBLIC KEY BLOCK-----\n"
        .to_vec()
}

fn public_then_secret() -> Vec<u8> {
    let mut out = public_binary();
    out.extend(packet(5, b"\x04invented secret key material"));
    out
}

fn armored_then_private() -> Vec<u8> {
    let mut out = public_armored();
    out.extend_from_slice(
        b"-----BEGIN PGP PRIVATE KEY BLOCK-----\n\nc2VjcmV0\n-----END PGP PRIVATE KEY BLOCK-----\n",
    );
    out
}

// ---------------------------------------------------------------- the loopback server ---

/// What the server answers for one path.
#[derive(Clone)]
enum Reply {
    Body(u16, Vec<u8>),
    Redirect(String),
    /// Read the request, then answer nothing until the server stops.
    Stall,
}

/// An HTTP/1.1 server on 127.0.0.1 for one test: it counts every connection, answers each path
/// from its table, and is stopped and joined when dropped. Its accept loop is bounded by that
/// stop flag and a test-length deadline, so nothing it starts outlives the test.
struct Server {
    port: u16,
    connections: Arc<AtomicUsize>,
    stop: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
}

impl Server {
    fn start(routes: &[(&str, Reply)]) -> Server {
        let listener = TcpListener::bind("127.0.0.1:0").expect("a loopback port");
        listener.set_nonblocking(true).expect("nonblocking accept");
        let port = listener.local_addr().expect("the port").port();
        let connections = Arc::new(AtomicUsize::new(0));
        let stop = Arc::new(AtomicBool::new(false));
        let routes: BTreeMap<String, Reply> = routes
            .iter()
            .map(|(path, reply)| ((*path).to_string(), reply.clone()))
            .collect();
        let thread = {
            let (connections, stop) = (connections.clone(), stop.clone());
            std::thread::spawn(move || {
                let deadline = Instant::now() + Duration::from_secs(120);
                while !stop.load(Ordering::SeqCst) && Instant::now() < deadline {
                    match listener.accept() {
                        Ok((stream, _)) => {
                            connections.fetch_add(1, Ordering::SeqCst);
                            serve(stream, &routes, &stop);
                        }
                        Err(_) => std::thread::sleep(Duration::from_millis(5)),
                    }
                }
            })
        };
        Server {
            port,
            connections,
            stop,
            thread: Some(thread),
        }
    }

    fn rewrite(&self) -> String {
        format!("{KEYS}=http://127.0.0.1:{}/", self.port)
    }

    fn connections(&self) -> usize {
        self.connections.load(Ordering::SeqCst)
    }
}

impl Drop for Server {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::SeqCst);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

fn serve(mut stream: TcpStream, routes: &BTreeMap<String, Reply>, stop: &AtomicBool) {
    let _ = stream.set_nonblocking(false);
    let _ = stream.set_read_timeout(Some(Duration::from_secs(5)));
    let mut request = Vec::new();
    let mut buf = [0u8; 1024];
    while !request.windows(4).any(|w| w == b"\r\n\r\n") {
        match stream.read(&mut buf) {
            Ok(0) | Err(_) => return,
            Ok(n) => request.extend_from_slice(&buf[..n]),
        }
    }
    let text = String::from_utf8_lossy(&request);
    let path = text.split_whitespace().nth(1).unwrap_or("/").to_string();
    let reply = routes
        .get(&path)
        .cloned()
        .unwrap_or(Reply::Body(404, b"not here\n".to_vec()));
    let (status, headers, body) = match reply {
        Reply::Body(status, body) => (status, String::new(), body),
        Reply::Redirect(to) => (302, format!("Location: {to}\r\n"), Vec::new()),
        Reply::Stall => {
            let until = Instant::now() + Duration::from_secs(30);
            while !stop.load(Ordering::SeqCst) && Instant::now() < until {
                std::thread::sleep(Duration::from_millis(10));
            }
            return;
        }
    };
    let head = format!(
        "HTTP/1.1 {status} X\r\nContent-Length: {}\r\n{headers}Connection: close\r\n\r\n",
        body.len()
    );
    let _ = stream.write_all(head.as_bytes());
    let _ = stream.write_all(&body);
}

