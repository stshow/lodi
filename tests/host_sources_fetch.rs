//! `signed_by_url`: a declared source's keyring by HTTPS URL (LD-366, S12).
//!
//! The plan never fetches; the apply fetches every keyring it needs through `src/fetch.rs`'s one
//! entry point, checks its digest (S5) and its framing (S4) — `sources::verify`, the one check a
//! keyring by path passes too — before the journal's first mutation, and writes nothing at all on
//! any failure. A keyring already at the managed path with the declared digest is never fetched
//! again.
//!
//! Every fetch here is a real HTTP exchange with a loopback server this file runs for the length
//! of one test (`Server`, stopped and joined on drop), reached through `LODI_FETCH_REWRITE` — the
//! product's own documented mirror seam — so the URL in the manifest is an `https://` one and the
//! bytes come over a socket. The `lodi` binary is run for the plan (`lodi switch --host
//! --dry-run`), the apply (`lodi switch --host`) and every failure a flag can reach, against a
//! fake machine (`tests/support/fakehost.rs`, LD-514, LD-522); the one case that needs time
//! limits shorter than `lodi`'s own (a server that never answers) drives the same apply in
//! process through `hostscope::apply_with` with a real `HttpFetcher` built with short limits.
//! Scratch roots only (`AGENTS.md` §8): every host command carries `--root`, under
//! `LODI_HOST_REQUIRE_ROOT=1`. The keyrings are generated byte strings
//! that pass or fail the S4 framing check; no real vendor key is anywhere in this file.

