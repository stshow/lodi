/// Shims for every program the apt backend reaches for, first on `PATH`: nothing installed, no
/// candidate, a refresh that "runs". No package manager runs here.
fn shims() -> PathBuf {
    static SETUP: Once = Once::new();
    static DIR: std::sync::OnceLock<PathBuf> = std::sync::OnceLock::new();
    let dir = DIR
        .get_or_init(|| support::scratch("sources-fetch-shims"))
        .clone();
    SETUP.call_once(|| {
        hostroot::shims();
        for (name, body) in [
            ("apt-get", "exit 0\n"),
            ("dpkg", "exit 0\n"),
            ("dpkg-query", "exit 0\n"),
            ("apt-mark", "exit 0\n"),
            // Fedora's two programs, for the one Fedora case: nothing reaches them there.
            ("dnf5", "exit 0\n"),
            ("rpm", "exit 0\n"),
            (
                "apt-cache",
                "case \"$1\" in\npolicy) shift; for n in \"$@\"; do printf '%s:\\n  Installed: (none)\\n  Candidate: (none)\\n' \"$n\"; done ;;\nesac\nexit 0\n",
            ),
        ] {
            let path = dir.join(name);
            fs::write(
                &path,
                format!(
                    "#!/bin/sh\n# A test-owned shim of tests/host_sources_fetch.rs. No package manager runs here.\n{body}"
                ),
            )
            .expect("a shim");
            fs::set_permissions(&path, fs::Permissions::from_mode(0o755)).expect("a shim mode");
        }
        let existing = std::env::var("PATH").unwrap_or_default();
        // SAFETY: every `PATH` access in this binary happens after this `Once` completes.
        unsafe { std::env::set_var("PATH", format!("{}:{existing}", dir.display())) };
    });
    dir
}

/// `[sources.docker]` with its keyring by URL.
fn by_url(path: &str, sha: &str) -> String {
    format!(
        "[sources.docker]\n\
         uris = [\"https://download.docker.com/linux/debian\"]\n\
         suites = [\"${{host.codename}}\"]\n\
         components = [\"stable\"]\n\
         signed_by_url = \"{KEYS}{path}\"\n\
         signed_by_sha256 = \"{sha}\"\n"
    )
}

/// `[sources.other]`, a valid source with its keyring beside the manifest.
fn by_path(sha: &str) -> String {
    format!(
        "[sources.other]\n\
         uris = [\"https://packages.example.invalid/debian\"]\n\
         suites = [\"bookworm\"]\n\
         components = [\"main\"]\n\
         signed_by = \"files/other.gpg\"\n\
         signed_by_sha256 = \"{sha}\"\n"
    )
}

/// A Debian machine whose config's `host.toml` is `manifest`, with the keyring `[sources.other]`
/// names beside it and a fresh index, so that only a changing source makes a plan refresh it.
fn armed(name: &str, manifest: &str) -> fakehost::Case {
    let case = fakehost::Case::new(name, fakehost::Machine::debian());
    case.set_manifest(manifest);
    case.write_beside("files/other.gpg", public_binary());
    settled(&case, "debian", "bookworm", manifest);
    case
}

/// `case` as lodi's first switch of it leaves it, before anything below is asked: the may-manage
/// marker in place, and the config's `lodi.lock` recording each `signed_by_url` key of `manifest`
/// by its declared digest. A switch fetches a key the lock does not record to record it (#702's
/// lock); one it records is fetched only by the apply that writes it, which is what this file
/// is about.
fn settled(case: &fakehost::Case, distro: &str, release: &str, manifest: &str) {
    case.root
        .write("etc/lodi/may-manage", "")
        .chmod("etc/lodi/may-manage", 0o644);
    let mut keys = BTreeMap::new();
    let (mut source, mut by_url) = (None, false);
    for line in manifest.lines() {
        if let Some(name) = line.strip_prefix("[sources.") {
            source = Some(name.trim_end_matches(']').to_string());
            by_url = false;
        } else if line.starts_with("signed_by_url = ") {
            by_url = true;
        } else if let Some(sha) = line.strip_prefix("signed_by_sha256 = ")
            && by_url
            && let Some(name) = &source
        {
            keys.insert(name.clone(), format!("sha256:{}", sha.trim_matches('"')));
        }
    }
    let mut lock = lodi::config::lock::Lock::default();
    lock.hosts.insert(
        "host.toml".to_string(),
        lodi::config::lock::HostSection {
            distro: distro.into(),
            release: release.into(),
            arch: "x86_64".into(),
            snapshot: None,
            pins: BTreeMap::new(),
            keys,
        },
    );
    let file = case.config().join("lodi.lock");
    fs::write(&file, lock.render()).expect("lodi.lock");
    fs::set_permissions(&file, fs::Permissions::from_mode(0o644)).expect("its mode");
}

/// An armed Debian root with `manifest` in place (`etc/lodi/host.toml`) and the keyring
/// `[sources.other]` names beside it, for the one case driven in process.
fn armed_in_place(name: &str, manifest: &str) -> Root {
    shims();
    let root = Root::new(name);
    root.debian_with(manifest);
    fs::create_dir_all(root.path("etc/lodi/files")).expect("the files directory");
    fs::write(root.path("etc/lodi/files/other.gpg"), public_binary()).expect("the keyring");
    root.write("var/lib/apt/lists/recorded_Packages", "recorded index\n");
    root
}

/// Everything below `dir`, as relative paths with a digest for each file.
fn tree(dir: &Path) -> BTreeMap<String, Option<String>> {
    let mut out = BTreeMap::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(next) = stack.pop() {
        let Ok(entries) = fs::read_dir(&next) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            let mut rel = path
                .strip_prefix(dir)
                .expect("below the root")
                .display()
                .to_string();
            // A journal is named by its time and a random id; its place is what is compared.
            if let Some(name) = rel.strip_prefix("var/lib/lodi/host/journal/") {
                rel = format!("var/lib/lodi/host/journal/<{}>", name.len());
            }
            // A switch logs every run, as the person, whatever it did: not a cache.
            if rel.contains("lodi/logs") || rel == "xdg-state/lodi" {
                continue;
            }
            let meta = fs::symlink_metadata(&path).expect("metadata");
            if meta.is_dir() {
                stack.push(path);
                out.insert(rel, None);
            } else {
                out.insert(rel, Some(sha256_hex(&fs::read(&path).unwrap_or_default())));
            }
        }
    }
    out
}

/// The scratch directories a `lodi` child is given for its store, its home and its temporary
/// files, so that anything it cached anywhere would show.
struct Elsewhere {
    dir: PathBuf,
}

impl Elsewhere {
    fn new(name: &str) -> Elsewhere {
        let dir = support::scratch(&format!("fetch-elsewhere-{name}"));
        for sub in ["store", "home", "tmp", "xdg-cache", "xdg-data", "xdg-state"] {
            fs::create_dir_all(dir.join(sub)).expect("a scratch directory");
        }
        Elsewhere { dir }
    }
}

impl Drop for Elsewhere {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.dir);
    }
}

/// A 1.x host verb's name, run as the 2.0 command that keeps it (`fakehost::Case::verb_env`:
/// `plan` is `switch --host --dry-run`, `apply` is `switch --host`) with `--root ROOT`, the
/// server's rewrite ahead of the fake's offline archive, one attempt, and every place a cache
/// could hide pointed into `elsewhere`.
fn lodi(verb: &str, case: &fakehost::Case, server: &Server, elsewhere: &Elsewhere) -> Output {
    lodi_with(verb, &[], case, server, elsewhere)
}

/// [`lodi`] with `extra` arguments.
fn lodi_with(
    verb: &str,
    extra: &[&str],
    case: &fakehost::Case,
    server: &Server,
    elsewhere: &Elsewhere,
) -> Output {
    let e = &elsewhere.dir;
    let rewrite = format!("{};{}", server.rewrite(), case.archive_server.rewrite());
    let path = |sub: &str| e.join(sub).display().to_string();
    case.verb_env(
        verb,
        extra,
        &[
            ("LODI_FETCH_REWRITE", &rewrite),
            ("LODI_HOME", &path("store")),
            ("TMPDIR", &path("tmp")),
            ("XDG_CACHE_HOME", &path("xdg-cache")),
            ("XDG_DATA_HOME", &path("xdg-data")),
            ("XDG_STATE_HOME", &path("xdg-state")),
        ],
    )
}

fn text(output: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    )
}

