/// A URI with user information, built at run time so that no file of the repository holds a
/// string of the shape the sanitization check (`AGENTS.md` §1.6) reads as an address.
fn userinfo(who: &str) -> String {
    format!("https://{who}{}a.example/d", '@')
}

#[test]
fn s2_a_uri_is_https_only_with_no_user_information_query_or_fragment() {
    for (uri, code, named) in [
        (
            "http://a.example/d",
            "E_UNSUPPORTED",
            "is not an https:// URI",
        ),
        (
            "ftp://a.example/d",
            "E_UNSUPPORTED",
            "is not an https:// URI",
        ),
        ("file:/srv/repo", "E_UNSUPPORTED", "is not an https:// URI"),
        ("a.example/d", "E_UNSUPPORTED", "is not an https:// URI"),
        (
            userinfo("user").as_str(),
            "E_UNSUPPORTED",
            "user information",
        ),
        (
            userinfo("user:pass").as_str(),
            "E_UNSUPPORTED",
            "user information",
        ),
        (
            "https://a.example/d?token=1",
            "E_UNSUPPORTED",
            "carries a query",
        ),
        ("https:///d", "E_UNSUPPORTED", "names no host"),
    ] {
        refuses(
            &one(
                "a",
                &keys(&format!("[\"{uri}\"]"), "[\"s\"]", "components = [\"c\"]\n"),
            ),
            code,
            named,
        );
    }
    // A fragment is refused by name too; `#` is also the S3 character, so its code is S3's, at
    // the value's own place, and the message names the fragment the manifest carries.
    let fragment = one(
        "a",
        &keys(
            "[\"https://a.example/d#x\"]",
            "[\"s\"]",
            "components = [\"c\"]\n",
        ),
    );
    let got = refused(&fragment);
    assert_eq!(got.len(), 1, "{got:#?}");
    assert_eq!(got[0].0, "E_TYPE", "{got:#?}");
    assert!(
        got[0].1.contains("carries a fragment (`#x`)") && got[0].1.contains("`#` starts a comment"),
        "{got:#?}"
    );
    assert!(got[0].1.ends_with("@host.toml:7:9"), "{got:#?}\n{fragment}");
    // The helper names it the same way where a URI is checked on its own.
    assert_eq!(
        lodi::hostscope::manifest::uri_problem("https://a.example/d#x"),
        Some(("E_UNSUPPORTED", "carries a fragment (`#…`)"))
    );
    parsed(&one(
        "a",
        &keys(
            "[\"HTTPS://A.example:8443/d/\"]",
            "[\"s\"]",
            "components = [\"c\"]\n",
        ),
    ));
}

/// S2 through the binary: the plan, over a scratch root, of a manifest whose `[sources]` URI
/// carries a fragment is refused `E_TYPE` naming the fragment at file:line:column, before
/// anything below the root is read or written, and so is the apply.
#[test]
fn s2_the_binary_refuses_a_uri_fragment_as_e_type_naming_it_at_its_place() {
    let case = Case::new("sources-fragment", docker_machine());
    docker(&case, &public_key(1), &[]);
    let manifest = case
        .manifest()
        .replace(DOCKER_URI, &format!("{DOCKER_URI}#main"));
    case.set_manifest(&manifest);
    let line = manifest
        .lines()
        .position(|line| line.starts_with("uris = "))
        .unwrap()
        + 1;
    let before = census(&case);
    for output in [case.plan(), case.apply(&[])] {
        assert_eq!(output.status.code(), Some(3), "{}", story(&output));
        let text = err(&output);
        assert!(text.contains("E_TYPE"), "{}", story(&output));
        assert!(
            text.contains("carries a fragment (`#main`)"),
            "{}",
            story(&output)
        );
        assert!(
            text.contains(&format!("host.toml:{line}:9")),
            "{}",
            story(&output)
        );
        assert!(case.log().is_empty(), "{:?}", case.log());
    }
    assert_eq!(census(&case), before, "nothing below the root was written");
}

#[test]
fn s3_a_value_that_would_break_a_stanza_is_e_type_at_its_place_literal_or_substituted() {
    // Literally, and through a variable that expands to the same bytes.
    let literal = one(
        "a",
        &keys(
            "[\"https://a.example\"]",
            "[\"bookworm\\nTrusted: yes\"]",
            "components = [\"c\"]\n",
        ),
    );
    let got = refused(&literal);
    assert_eq!(got.len(), 1, "{got:#?}");
    assert_eq!(got[0].0, "E_TYPE");
    assert!(got[0].1.contains("control character"), "{got:#?}");
    // The file, the line and the column of the value itself.
    assert!(got[0].1.ends_with("@host.toml:8:11"), "{got:#?}\n{literal}");

    let through = format!(
        "{HEAD}[vars]\nsuite = \"bookworm\\nTrusted: yes\"\n\n[sources.a]\n{}",
        keys(
            "[\"https://a.example\"]",
            "[\"${vars.suite}\"]",
            "components = [\"c\"]\n"
        )
    );
    let got = refused(&through);
    assert_eq!(got.len(), 1, "{got:#?}");
    assert_eq!(got[0].0, "E_TYPE");
    assert!(got[0].1.contains("@host.toml:"), "{got:#?}");

    for (value, problem) in [
        ("", "is empty"),
        ("a b", "whitespace"),
        ("a\\tb", "control character"),
        ("a#b", "`#`"),
        ("a\\u0000", "control character"),
    ] {
        for field in ["suites", "components", "types", "architectures"] {
            let mut uris = "[\"https://a.example\"]".to_string();
            let mut suites = "[\"s\"]".to_string();
            let mut rest = "components = [\"c\"]\n".to_string();
            match field {
                "suites" => suites = format!("[\"{value}\"]"),
                "components" => rest = format!("components = [\"{value}\"]\n"),
                other => rest.push_str(&format!("{other} = [\"{value}\"]\n")),
            }
            if field == "uris" {
                uris = format!("[\"{value}\"]");
            }
            refuses(&one("a", &keys(&uris, &suites, &rest)), "E_TYPE", problem);
        }
    }

    // Whatever passes renders one line per field and no line anyone else wrote: no stanza can
    // hold a `Trusted` line.
    let manifest = parsed(&one(
        "a",
        &keys(
            "[\"https://a.example\"]",
            "[\"s\"]",
            "components = [\"c\"]\n",
        ),
    ));
    let text = sourceset::render(&sources::stanza(&manifest.sources["a"], Format::Binary));
    assert!(!text.to_ascii_lowercase().contains("trusted"), "{text}");
    assert_eq!(text.lines().count(), 6, "{text}");
}

