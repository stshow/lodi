// ------------------------------------------------------------------------------- keyrings ---

/// A new-format packet: tag, one-octet length, body.
fn packet(tag: u8, body: &[u8]) -> Vec<u8> {
    assert!(body.len() < 192);
    let mut out = vec![0xC0 | tag, body.len() as u8];
    out.extend_from_slice(body);
    out
}

/// An old-format packet with a two-octet length.
fn old_packet(tag: u8, body: &[u8]) -> Vec<u8> {
    let mut out = vec![0x80 | (tag << 2) | 1];
    out.extend_from_slice(&(body.len() as u16).to_be_bytes());
    out.extend_from_slice(body);
    out
}

/// A binary "public keyring": a public-key packet, a user id, a public subkey. The bodies are
/// invented bytes; only the framing is real.
fn public_key(seed: u8) -> Vec<u8> {
    let mut out = packet(6, &[4, 0, 0, 0, seed, 22, 1, 2, 3]);
    out.extend(packet(13, b"Test Signing Key (generated)"));
    out.extend(old_packet(14, &[4, 0, 0, 0, seed, 22, 9, 9]));
    out
}

const ARMORED: &str = "-----BEGIN PGP PUBLIC KEY BLOCK-----\n\n\
                       bm90IGEga2V5OiBnZW5lcmF0ZWQgZm9yIGEgdGVzdA==\n=AAAA\n\
                       -----END PGP PUBLIC KEY BLOCK-----\n";

fn armored() -> Vec<u8> {
    ARMORED.as_bytes().to_vec()
}

/// A generated armored keyring: the given public block, then a private key block whose marker
/// stands mid-line, after other text on the same line — never a line of its own.
fn midline_private(public: &str) -> Vec<u8> {
    format!(
        "{public}comment: -----BEGIN PGP PRIVATE KEY BLOCK-----\nSECRET-MATERIAL-XYZ\n\
         -----END PGP PRIVATE KEY BLOCK-----\n"
    )
    .into_bytes()
}

fn sha(bytes: &[u8]) -> String {
    sha256_hex(bytes)
}

