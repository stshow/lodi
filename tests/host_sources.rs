// ------------------------------------------------------------------------ compatibility ---
//
// §7: a 1.2 `host.toml` — every host manifest committed under `tests/fixtures/host/import/`, and
// one `[files]` walk — plans byte-identically, and its apply leaves byte-identical lock and
// journal bytes, against goldens under `tests/fixtures/host/compat-1.2/` recorded from the 1.2.0
// binary by these same walks.
//
// Recording (never a validation command): a `git worktree` of the 1.2.0 release commit outside
// the repository, built with the repository's toolchain, then `LODI_RECORD_EXPECTED=1
// LODI_COMPAT_BINARY=<that build's lodi> cargo test --locked --test host_sources compat_1_2`, and
// the worktree removed (`tests/fixtures/host/compat-1.2/README.md`). What a walk cannot hold
// still is written as a placeholder, the same way for both binaries: the scratch root `<root>`,
// the fake machine's directory `<fake>`, every UTC instant `<time>`, a journal id `<journal>`, a
// backup's stamp, the invoking user's ids, and the running binary's own version, which is written
// back as the recorded one. Every other byte is compared as recorded.

const COMPAT: &str = "tests/fixtures/host/compat-1.2";
/// The version of the binary that recorded the goldens.
const RECORDED: &str = "1.2.0";

fn compat_binary() -> std::ffi::OsString {
    std::env::var_os("LODI_COMPAT_BINARY")
        .unwrap_or_else(|| std::ffi::OsString::from(env!("CARGO_BIN_EXE_lodi")))
}

fn compat_recording() -> bool {
    std::env::var_os("LODI_RECORD_EXPECTED").is_some()
        && std::env::var_os("LODI_COMPAT_BINARY").is_some()
}

/// Every `YYYY-MM-DDTHH:MM:SSZ` and `YYYYMMDDTHHMMSSZ-<32 hex>`, masked.
fn mask_times(text: &str) -> String {
    let bytes: Vec<char> = text.chars().collect();
    let mut out = String::new();
    let mut i = 0;
    let digit = |j: usize, from: &[char]| from.get(j).is_some_and(|c| c.is_ascii_digit());
    while i < bytes.len() {
        // 2026-09-24T16:03:42Z (and with fractional seconds)
        let iso = (0..4).all(|k| digit(i + k, &bytes))
            && bytes.get(i + 4) == Some(&'-')
            && bytes.get(i + 10) == Some(&'T')
            && bytes.get(i + 13) == Some(&':');
        if iso {
            let mut j = i + 19;
            while bytes
                .get(j)
                .is_some_and(|c| c.is_ascii_digit() || *c == '.')
            {
                j += 1;
            }
            if bytes.get(j) == Some(&'Z') {
                out.push_str("<time>");
                i = j + 1;
                continue;
            }
        }
        // 20260924T160342Z, then -<32 hex> for a journal id, or -<9 digits> for a backup
        let stamp = (0..8).all(|k| digit(i + k, &bytes))
            && bytes.get(i + 8) == Some(&'T')
            && (9..15).all(|k| digit(i + k, &bytes))
            && bytes.get(i + 15) == Some(&'Z');
        if stamp {
            let mut j = i + 16;
            if bytes.get(j) == Some(&'-') {
                let mut k = j + 1;
                while bytes.get(k).is_some_and(|c| c.is_ascii_hexdigit()) {
                    k += 1;
                }
                if k - j - 1 == 32 {
                    out.push_str("<journal>");
                    i = k;
                    continue;
                }
                if k - j - 1 == 9 {
                    j = k;
                }
            }
            out.push_str("<stamp>");
            i = j;
            continue;
        }
        out.push(bytes[i]);
        i += 1;
    }
    out
}

fn normalize(case: &Case, text: &str) -> String {
    let (uid, gid) = hostroot::ids(&case.root);
    let mut text = text
        .replace(&case.root.dir.display().to_string(), "<root>")
        .replace(&case.base().display().to_string(), "<fake>")
        .replace(
            &format!("lodi {}", lodi::schema::LODI_VERSION),
            &format!("lodi {RECORDED}"),
        )
        .replace(
            &format!("\"lodiVersion\":\"{}\"", lodi::schema::LODI_VERSION),
            &format!("\"lodiVersion\":\"{RECORDED}\""),
        );
    text = mask_times(&text);
    for (prefix, id) in [("\"uid\":", uid), ("\"gid\":", gid), ("\"euid\":", uid)] {
        text = text.replace(&format!("{prefix}{id}"), &format!("{prefix}<id>"));
    }
    text.replace(&format!("owner {uid}:{gid}"), "owner <uid>:<gid>")
        .replace(&format!("\"owner\": \"{uid}\""), "\"owner\": \"<uid>\"")
        .replace(&format!("\"group\": \"{gid}\""), "\"group\": \"<gid>\"")
        .replace(&format!("owner = \"{uid}\""), "owner = \"<uid>\"")
        .replace(&format!("group = \"{gid}\""), "group = \"<gid>\"")
}

/// One walk: plan, apply, the lock and the journal it left, and the plan after it.
fn compat_walk(case: &Case) -> String {
    let binary = compat_binary();
    // The one line an earlier release's `[files]` manifest prints now (si-1) is taken out.
    let legacy = !compat_recording() && compat::has_files_table(case);
    let run = |label: &str, verb: &str| {
        let output = case.verb_by(&binary, verb, &[]);
        format!(
            "== {label}: exit {:?}\n-- stdout\n{}-- stderr\n{}",
            output.status.code(),
            out(&output),
            compat::without_legacy_warning(&err(&output), legacy)
        )
    };
    let mut transcript = run("plan", "plan");
    transcript.push_str(&run("apply", "apply"));
    let lock = case.root.read("etc/lodi/host.lock");
    let journal = journals(&case.root)
        .first()
        .map(|path| fs::read_to_string(path).unwrap())
        .unwrap_or_default();
    transcript.push_str(&format!("== host.lock\n{lock}\n== journal\n{journal}"));
    transcript.push_str(&run("plan after", "plan"));
    normalize(case, &transcript)
}

/// The names a committed import manifest declares, each offered by the fake machine.
fn declared_names(text: &str) -> Vec<String> {
    let mut names = Vec::new();
    for line in text.lines() {
        let trimmed = line.trim();
        if line.starts_with("  \"") && trimmed.ends_with("\",") {
            let name = trimmed.trim_end_matches(',').trim_matches('"').to_string();
            if !names.contains(&name) {
                names.push(name);
            }
        }
    }
    names
}

fn compat_check(name: &str, transcript: &str) {
    let path = repo().join(COMPAT).join(format!("{name}.txt"));
    if compat_recording() {
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, transcript).unwrap();
        return;
    }
    let golden = fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("{}: {e}; record it (README)", path.display()));
    // A committed import manifest's comments are this build's, so its digest is masked (si-1).
    assert_eq!(
        compat::mask_manifest_digest(transcript),
        compat::mask_manifest_digest(&golden),
        "{name}: this build differs from 1.2.0 ({})",
        path.display()
    );
}

#[test]
fn compat_1_2_every_committed_host_manifest_plans_and_applies_as_1_2_did() {
    let fixtures = repo().join("tests/fixtures/host/import");
    let mut walked = 0;
    let mut dirs: Vec<PathBuf> = Vec::new();
    for distro in fs::read_dir(&fixtures).unwrap().flatten() {
        if !distro.path().is_dir() {
            continue;
        }
        for scenario in fs::read_dir(distro.path()).unwrap().flatten() {
            if scenario.path().join("expected.toml").is_file() {
                dirs.push(scenario.path());
            }
        }
    }
    dirs.sort();
    for dir in dirs {
        let distro = dir
            .parent()
            .unwrap()
            .file_name()
            .unwrap()
            .to_string_lossy()
            .into_owned();
        let scenario = dir.file_name().unwrap().to_string_lossy().into_owned();
        let label = format!("{distro}-{scenario}");
        let arch = distro == "arch";
        // Arch import now writes a different snapshot and comment. Keep the pre-change
        // input this golden measured; an unpinned walk must not silently re-record it.
        let input = if arch {
            repo()
                .join("tests/fixtures/host/compat-1.3")
                .join(format!("{label}.toml"))
        } else {
            dir.join("expected.toml")
        };
        let text = fs::read_to_string(input).unwrap();
        let mut machine = if arch {
            Machine::arch()
        } else {
            Machine::debian()
        };
        for name in declared_names(&text) {
            if !machine.installed.iter().any(|p| p.name == name) {
                machine = machine.offering(Pkg::new(&name).repo(Some(if arch {
                    "extra"
                } else {
                    "main"
                })));
            }
        }
        let case = Case::new(&format!("compat-{label}"), machine);
        if let Some(release) = distro.strip_prefix("ubuntu-") {
            let codename = text
                .lines()
                .find_map(|line| line.strip_prefix("# distribution: ubuntu ("))
                .and_then(|rest| rest.strip_suffix(')'))
                .expect("an ubuntu codename");
            case.root.write(
                "etc/os-release",
                &format!(
                    "NAME=\"Ubuntu\"\nID=ubuntu\nID_LIKE=debian\nVERSION_ID=\"{release}\"\n\
                     VERSION_CODENAME={codename}\n"
                ),
            );
        }
        // The unpinned form of the file: its `[host] snapshot` is live since M-Pin (LD-395's
        // D-A), and what this walk holds to 1.2 is a manifest with nothing pinned, with the
        // minimum the import wrote before 1.4.0 (LD-398).
        // Nor the [system] table the import writes since si-1, which 1.2 did not know.
        case.set_manifest(
            &compat::without_system(&fakehost::without_snapshot(&text)).replace(
                "min_lodi_version = \">=1.4.0\"\n",
                "min_lodi_version = \">=1.1.1\"\n",
            ),
        );
        compat_check(&label, &compat_walk(&case));
        walked += 1;
    }
    // Twelve at LD-365, five from LD-367, two ambiguous-attribution scenarios from si-1's
    // validator repair, and two extra-suite scenarios from LD-414.
    assert_eq!(walked, 23, "every committed host manifest is walked");
}

