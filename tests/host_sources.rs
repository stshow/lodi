#[test]
fn s4_the_keyring_framing_decides_its_name_and_secret_keys_never_pass() {
    assert_eq!(sniff(&public_key(1)), Ok(Format::Binary));
    assert_eq!(sniff(&armored()), Ok(Format::Armored));
    // Two public keys in one file: accepted; Signed-By trusts every key in it (the docs say so).
    let mut two = public_key(1);
    two.extend(public_key(2));
    assert_eq!(sniff(&two), Ok(Format::Binary));
    // Public then secret: a secret-key or secret-subkey packet anywhere is refused.
    for tag in [5u8, 7] {
        let mut mixed = public_key(1);
        mixed.extend(packet(tag, &[4, 0, 0, 0, 1, 2]));
        assert_eq!(sniff(&mixed), Err(Refusal::Secret), "tag {tag}");
        let mut old = public_key(1);
        old.extend(old_packet(tag, &[4, 0, 0, 0, 1, 2]));
        assert_eq!(sniff(&old), Err(Refusal::Secret), "old tag {tag}");
    }
    assert_eq!(sniff(&packet(5, &[4, 0])), Err(Refusal::Secret));
    // An armored public block followed by a private one.
    let both = format!(
        "{ARMORED}-----BEGIN PGP PRIVATE KEY BLOCK-----\n\nAAAA\n-----END PGP PRIVATE KEY BLOCK-----\n"
    );
    assert_eq!(sniff(both.as_bytes()), Err(Refusal::Secret));
    // The private block's marker anywhere, not only as a line of its own: mid-line after other
    // text, indented, inside the public block's body, and in bytes that are not UTF-8.
    assert_eq!(sniff(&midline_private(ARMORED)), Err(Refusal::Secret));
    let body = "bm90IGEga2V5OiBnZW5lcmF0ZWQgZm9yIGEgdGVzdA==";
    for placed in [
        ARMORED.replace(
            body,
            &format!("{body}-----BEGIN PGP PRIVATE KEY BLOCK-----"),
        ),
        ARMORED.replace(
            body,
            &format!("  -----BEGIN PGP PRIVATE KEY BLOCK-----x{body}"),
        ),
        format!("{ARMORED}trailing words -----BEGIN PGP PRIVATE KEY BLOCK----- and more"),
    ] {
        assert_eq!(sniff(placed.as_bytes()), Err(Refusal::Secret), "{placed}");
    }
    let mut not_utf8 = armored();
    not_utf8.extend([0xff, 0xfe]);
    not_utf8.extend(b"-----BEGIN PGP PRIVATE KEY BLOCK-----");
    assert_eq!(sniff(&not_utf8), Err(Refusal::Secret));
    let mut after_binary = public_key(1);
    after_binary.extend(b"x-----BEGIN PGP PRIVATE KEY BLOCK-----");
    assert_eq!(sniff(&after_binary), Err(Refusal::Secret));
    // Truncated framing, trailing bytes, a first packet that is not a public key, and text.
    let whole = public_key(1);
    assert_eq!(sniff(&whole[..whole.len() - 1]), Err(Refusal::NotKeyring));
    let mut trailing = public_key(1);
    trailing.push(0x00);
    assert_eq!(sniff(&trailing), Err(Refusal::NotKeyring));
    assert_eq!(
        sniff(&packet(13, b"a user id first")),
        Err(Refusal::NotKeyring)
    );
    for text in [
        &b""[..],
        b"<!DOCTYPE html><html><body>moved</body></html>\n",
        b"just some words\n",
        b"-----BEGIN PGP SIGNATURE-----\n\nAAAA\n-----END PGP SIGNATURE-----\n",
    ] {
        assert_eq!(sniff(text), Err(Refusal::NotKeyring), "{text:?}");
    }
    assert_eq!(Refusal::Secret.text(), "holds secret key material");
    assert_eq!(
        Refusal::NotKeyring.text(),
        "is not an OpenPGP public keyring"
    );
}

