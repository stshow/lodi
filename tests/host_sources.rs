/// A real apply of `case`, held at `hold`, killed there; returns the journal it left.
fn crash(case: &Case, hold: Hold) -> journal::Record {
    let path = case.fake_path();
    let mut child = hold.spawn_with(&case.root, &[("PATH", &path)]);
    hold.wait_held();
    kill(&mut child);
    let files = journals(&case.root);
    journal::read(files.last().expect("a journal")).expect("the journal reads")
}

/// Whether a stanza below the root names a keyring that is not there.
fn stanza_names_a_missing_keyring(case: &Case) -> bool {
    let text = case.root.read(STANZA);
    text.lines()
        .find_map(|line| line.strip_prefix("Signed-By: "))
        .is_some_and(|keyring| !case.root.exists(keyring))
}

#[test]
fn s9_a_crash_at_each_mutation_of_the_step_is_classified_and_never_leaves_a_stanza_naming_a_missing_keyring()
 {
    // 1. At the keyring's write: nothing of the source is there; the step is incomplete.
    let case = Case::new("sources-crash-keyring", docker_machine());
    docker(&case, &public_key(1), &[]);
    let record = crash(&case, Hold::at_write_of(&case.root, "lodi-docker.gpg"));
    assert!(matches!(
        record.classify(&case.root.dir),
        Classification::Incomplete { ref action, .. } if action == "s1.1"
    ));
    assert!(!case.root.exists(STANZA) && !stanza_names_a_missing_keyring(&case));
    assert!(case.apply(&[]).status.success());

    // 2. At the stanza's write over an original it keeps first: the copy is taken and the old
    //    stanza still stands, which is neither state — ambiguous, until a human resolves it.
    let case = Case::new("sources-crash-stanza", docker_machine());
    docker(&case, &public_key(1), &[]);
    case.root.write(
        STANZA,
        "# a hand-made file that is not a stanza lodi wrote\n",
    );
    let record = crash(&case, Hold::at_write_of(&case.root, "lodi-docker.sources"));
    assert!(case.root.exists(KEYRING_GPG));
    assert!(!stanza_names_a_missing_keyring(&case));
    match record.classify(&case.root.dir) {
        Classification::Ambiguous { action, .. } => assert_eq!(action, "s1.2"),
        other => panic!("expected ambiguous, got {other:?}"),
    }
    let refused = case.apply(&[]);
    assert_eq!(refused.status.code(), Some(8), "{}", story(&refused));
    assert!(
        err(&refused).contains("E_JOURNAL_AMBIGUOUS"),
        "{}",
        story(&refused)
    );
    // The operator looked, and the machine is as they want it: they say so by the journal's id.
    let resolved = case.apply(&["--resolved", &record.id]);
    assert!(resolved.status.success(), "{}", story(&resolved));
    assert!(!stanza_names_a_missing_keyring(&case));

    // 3. At the restore of a stanza the failed refresh puts back: held at its second write,
    //    after the first put the new bytes in. The keyring was never touched.
    let case = Case::new("sources-crash-restore", docker_machine());
    docker(&case, &public_key(1), &[]);
    assert!(case.apply(&[]).status.success());
    let text = case
        .manifest()
        .replace("suite = \"bookworm\"", "suite = \"trixie\"");
    case.set_manifest(&text);
    fail_update(&case, "fail", "E: failed");
    let record = crash(
        &case,
        Hold::at_write_of(&case.root, "lodi-docker.sources").nth(2),
    );
    assert!(matches!(
        record.classify(&case.root.dir),
        Classification::Incomplete { ref action, .. } if action == "s1.1.restore"
    ));
    assert!(!stanza_names_a_missing_keyring(&case));
    clear_update(&case);
    assert!(case.apply(&[]).status.success());

    // 4. At the restore of a created stanza, before it is removed, and at the restore of the
    //    created keyring, after the stanza was: the stanza never outlives its keyring.
    for (name, held, expect) in [
        (
            "sources-crash-remove-stanza",
            "lodi-docker.sources",
            "s1.2.restore",
        ),
        (
            "sources-crash-remove-keyring",
            "lodi-docker.gpg",
            "s1.1.restore",
        ),
    ] {
        let case = Case::new(name, docker_machine());
        docker(&case, &public_key(1), &[]);
        fail_update(&case, "fail", "E: failed");
        let record = crash(&case, Hold::at_open_of(&case.root, held));
        assert!(
            matches!(
                record.classify(&case.root.dir),
                Classification::Incomplete { ref action, .. } if action == expect
            ),
            "{:?}",
            record.classify(&case.root.dir)
        );
        assert!(!stanza_names_a_missing_keyring(&case), "{name}");
        clear_update(&case);
        let again = case.apply(&[]);
        assert!(again.status.success(), "{}", story(&again));
        assert!(case.root.exists(STANZA) && !stanza_names_a_missing_keyring(&case));
    }
}

