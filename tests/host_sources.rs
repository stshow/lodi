/// A manifest with one `[sources.NAME]` per `(name, keyring file, keyring bytes, suite)` and the
/// given packages; each keyring is written under the manifest's directory.
fn with_sources(case: &Case, sources: &[(&str, &str, &[u8], &str)], packages: &[&str]) {
    let mut text = HEAD.to_string();
    for (name, file, bytes, suite) in sources {
        case.root.write(&format!("etc/lodi/files/{file}"), "");
        fs::write(case.root.path(&format!("etc/lodi/files/{file}")), bytes).unwrap();
        text.push_str(&format!(
            "[sources.{name}]\nuris = [\"https://{name}.example/debian\"]\nsuites = [\"{suite}\"]\n\
             components = [\"stable\"]\nsigned_by = \"files/{file}\"\nsigned_by_sha256 = \"{}\"\n\n",
            sha(bytes)
        ));
    }
    if !packages.is_empty() {
        let names: Vec<String> = packages.iter().map(|p| format!("\"{p}\"")).collect();
        text.push_str(&format!("[packages]\ncommon = [{}]\n", names.join(", ")));
    }
    case.set_manifest(&text);
}

/// The Docker manifest of the brief, with the keyring given.
fn docker(case: &Case, keyring: &[u8], packages: &[&str]) {
    case.root.write("etc/lodi/files/keyrings/docker.key", "");
    fs::write(
        case.root.path("etc/lodi/files/keyrings/docker.key"),
        keyring,
    )
    .unwrap();
    let names: Vec<String> = packages.iter().map(|p| format!("\"{p}\"")).collect();
    case.set_manifest(&format!(
        "{HEAD}[vars]\nsuite = \"bookworm\"\n\n[sources.docker]\nuris = [\"{DOCKER_URI}\"]\n\
         suites = [\"${{vars.suite}}\"]\ncomponents = [\"stable\"]\narchitectures = [\"amd64\"]\n\
         signed_by = \"files/keyrings/docker.key\"\nsigned_by_sha256 = \"{}\"\n\n\
         [packages]\ncommon = [{}]\n",
        sha(keyring),
        names.join(", ")
    ));
}

/// Every regular file below the root, relative, with its bytes' digest — what "nothing was
/// written" is checked against.
fn census(case: &Case) -> Vec<(String, String)> {
    fn visit(base: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
        let Ok(entries) = fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            let meta = fs::symlink_metadata(&path).unwrap();
            if meta.is_dir() {
                visit(base, &path, out);
            } else {
                out.push((
                    path.strip_prefix(base).unwrap().display().to_string(),
                    format!(
                        "{}:{}",
                        sha(&fs::read(&path).unwrap_or_default()),
                        meta.mtime_nsec()
                    ),
                ));
            }
        }
    }
    let mut out = Vec::new();
    visit(&case.root.dir, &case.root.dir, &mut out);
    out.sort();
    out
}

